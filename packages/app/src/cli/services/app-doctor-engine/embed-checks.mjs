/**
 * Embeds the versioned semantic-check markdown so the bundled CLI does not
 * depend on runtime assets. The markdown files remain the source of truth.
 */
import {readFileSync, readdirSync, writeFileSync} from 'node:fs'
import {dirname, join} from 'node:path'
import {fileURLToPath} from 'node:url'

const engineRoot = dirname(fileURLToPath(import.meta.url))
const checksDirectory = join(engineRoot, 'checks')
const instructionsPath = join(engineRoot, 'INSTRUCTIONS.md')
const outputPath = join(checksDirectory, 'embedded.ts')
const files = readdirSync(checksDirectory)
  .filter((file) => file.endsWith('.md'))
  .sort()
const sources = files.map((file) => readFileSync(join(checksDirectory, file), 'utf8'))
const instructions = readFileSync(instructionsPath, 'utf8')

const output = `// AUTO-GENERATED by app-doctor-engine/embed-checks.mjs — do not edit.
// Sources of truth: adjacent checks/*.md files and ../INSTRUCTIONS.md.
/* eslint-disable no-restricted-syntax, no-template-curly-in-string */

// prettier-ignore
export const EMBEDDED_CHECK_SOURCES: ReadonlyArray<string> = ${JSON.stringify(sources, null, 2)};

// prettier-ignore
export const EMBEDDED_APP_DOCTOR_INSTRUCTIONS = ${JSON.stringify(instructions)};
`

writeFileSync(outputPath, output)
console.log(
  `Embedded ${files.length} semantic checks and App Doctor instructions in app-doctor-engine/checks/embedded.ts`,
)
