import {CommandData, CommandWithMarkdown, extractCommandData} from './generate.js'
import {testWithTempDir as test} from '@shopify/cli-kit/node/testing/test-with-temp-dir'
import {joinPath} from '@shopify/cli-kit/node/path'
import {describe, vi, expect} from 'vitest'

const testCommand: CommandWithMarkdown = {
  aliases: [],
  args: {},
  flags: {
    flag1: {
      name: 'flag1',
      type: 'option',
      char: 'f',
      description: 'flag description',
    },
    flag2: {
      name: 'flag2',
      type: 'boolean',
      char: 'a',
      description: 'another flag description',
      env: 'FLAG_ENV',
      allowNo: false,
    },
  },
  descriptionWithMarkdown: 'command markdown description',
  description: 'command description',
  summary: 'command summary',
  hidden: false,
  hiddenAliases: [],
  id: 'topic:test-command',
  load: () => Promise.resolve({} as any),
}

const commandData: CommandData = {
  commandName: 'topic test-command',
  fileName: 'topic-test-command',
  interfaceName: 'topictestcommand',
}

describe('extractCommandData', () => {
  test('returns the correct data', () => {
    expect(extractCommandData(testCommand)).toEqual(commandData)
  })
})

describe('writeCommandFlagInterface', () => {
  test('calls writeFile with the correct content', async ({tempDir}) => {
    vi.resetModules()
    const path = await import('@shopify/cli-kit/node/path')
    const fs = await import('@shopify/cli-kit/node/fs')
    vi.spyOn(path, 'cwd').mockReturnValue(tempDir)
    const writeFile = vi.spyOn(fs, 'writeFile')
    const {writeCommandFlagInterface} = await import('./generate.js')
    await writeCommandFlagInterface(testCommand, commandData)

    expect(writeFile).toHaveBeenCalledWith(
      joinPath(tempDir, 'docs-shopify.dev/commands/interfaces/topic-test-command.interface.ts'),
      `// This is an autogenerated file. Don't edit this file manually.
/**
 * The following flags are available for the \`topic test-command\` command:
 * @publicDocs
 */
export interface topictestcommand {
  /**
   * flag description
   *
   */
  '-f, --flag1 <value>'?: string

  /**
   * another flag description
   * @environment FLAG_ENV
   */
  '-a, --flag2'?: ''
}
`,
    )
  })

  test('calls writeFile with the correct content for a command with no flags', async ({tempDir}) => {
    vi.resetModules()
    const path = await import('@shopify/cli-kit/node/path')
    const fs = await import('@shopify/cli-kit/node/fs')
    vi.spyOn(path, 'cwd').mockReturnValue(tempDir)
    const writeFile = vi.spyOn(fs, 'writeFile')
    const {writeCommandFlagInterface} = await import('./generate.js')
    await writeCommandFlagInterface({...testCommand, flags: {}}, commandData)

    expect(writeFile).toHaveBeenCalledWith(
      joinPath(tempDir, 'docs-shopify.dev/commands/interfaces/topic-test-command.interface.ts'),
      `// This is an autogenerated file. Don't edit this file manually.
/**
 * The following flags are available for the \`topic test-command\` command:
 * @publicDocs
 */
export interface topictestcommand {

}
`,
    )
  })
})
